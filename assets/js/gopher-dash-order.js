/* ═══════════════════════════════════════════════════════════════════════════
   gopher-dash-order.js — THE ONE MAPPING from a web dashboard request to the
   server's order shape.

   WHY
   ---
   Owner ruling (John, 2026-10-15): "Port the app's logic + drop the demos". The
   requester dashboard in gopher-request.html now runs the Request APP's own
   helpers (Final/assets/js/app-shared/, generated by scripts/sync-app-helpers.py
   and exposed by gopher-app-shared.js as window.GopherAppShared). Those helpers
   read the SERVER's order fields — aasm_state, payment_status, disputed,
   requestor_alerts, photo_step_resolved and so on — so every web request record
   carries them, under the server's names, in `r.order`.

   THE CONTRACT
   ------------
     r.order  is a GET /orders/v3 row (and the GET /orders/:id fields the live
              screen reads), field for field. The dashboard renders the Home
              card, the step bar, the pills and the cancel / confirm / dispute
              doors from r.order through the app helpers, and from nothing else.

     sync(r)  (re)builds r.order from the web's local simulation state. It is the
              ONLY place that translation happens. Call it after any change to a
              request; the renderers call it before they read.

   WHEN THE REAL API IS WIRED: set `r.order = <the API row>` and give it
   `__source: 'api'`. sync() then leaves it alone, and the renderers already
   speak its language — nothing else changes. Until then the web's simulation
   (seeded demo records, the request flow, Hire, and the PT harness) writes the
   web fields listed below, and sync() derives the server fields from them.

   WEB FIELD (simulation)                    →  SERVER FIELD (r.order)
   ─────────────────────────────────────────    ──────────────────────────────
   hired worker (interestedWorkers / live.crew)  gopher_id, gopher{first_name,…}
   live.statusSteps (the worker's progress,      aasm_state: pending → accepted
     written by startJob and by the Go app over   | scheduled → picked_up →
     the PT bridge), awaitingConfirmation,         purchased → delivered
     confirmed
   scheduledForLater, requestScheduleTime        request_schedule_later, _time
   deliveryEta (open-until, when the flow has it) delivery_eta
   confirmed / paymentFailed + stripeError       payment_status, stripe_error
   unviewed offers, bids, counters, adjustment   requestor_alerts{order_gophers,
                                                   bids, counter, cogs, …}
   pendingAdjustment                             has_active_cog
   disputeState 'disputed', disputedAt,          disputed, disputed_at,
     disputeReason, unableToDispute,               dispute_reason, unable_to_dispute,
     disputeResolvedAt, disputeResolution          is_dispute_unable_to_resolve,
                                                   dispute_resolved_at, _resolution
   noShow (a worker-raised review)               disputed + the server's reason
   completion photos / photoStepResolved         photo_step_resolved
   noShowReminded, noShowRemindedAt              requestor_reminded, _at
   __ptGopherCancelled + __ptCancelReason (the   gopher_released_at,
     Go app's cancel over PT), until the           cancellation_reason
     requester picks "Assign new worker"
   category / cat / reviewSnapshot.category      category_type, title
   dropoffs / pickups / snapshot addresses       address, dropoff_address
   reviewSnapshot.costOfItems                    cost_of_goods (cents)
   perWorkerCost × (Labor ? workersNeeded : 1)   offer (cents)   — RQ-51

   Pure: no DOM, no storage, no network. Loads as a classic script (window
   .GopherDashOrder) and under node (module.exports) so the web checks can run it.
   ═══════════════════════════════════════════════════════════════════════════ */
(function (root) {
  'use strict';

  /* The web's category codes → the server's stored category_type. "Other" is
     what the server stores for a Custom Task (the app's categoryLabel turns it
     back into "Custom Task" for people). */
  var CATEGORY_TYPE = {
    delivery: 'Delivery',
    ride: 'Need a Ride',
    moving: 'Moving',
    junk: 'Junk Removal',
    home: 'Home Services',
    labor: 'Hourly / Day Labor',
    yard: 'Yard Project',
    other: 'Other',
    custom: 'Other'
  };
  /* The same, from a display name (reviewSnapshot.category and history rows). */
  var NAME_TYPE = {
    'delivery': 'Delivery', 'need a ride': 'Need a Ride', 'ride': 'Need a Ride',
    'moving': 'Moving', 'junk removal': 'Junk Removal', 'home services': 'Home Services',
    'handyman': 'Home Services', 'hourly / day labor': 'Hourly / Day Labor',
    'day labor': 'Hourly / Day Labor', 'labor': 'Hourly / Day Labor',
    'yard project': 'Yard Project', 'yard work': 'Yard Project',
    'custom task': 'Other', 'other': 'Other'
  };

  /* The three payment states GET /orders/v3 admits on the requester's Home
     (controllers/order/retrieve.js, the `payment_status` filter). */
  var HOME_PAYMENT = ['authorized', 'pending', 'requires_payment_method'];
  var HOME_STATES = ['pending', 'accepted', 'picked_up', 'purchased', 'scheduled', 'delivered'];
  var DAY_MS = 24 * 60 * 60 * 1000;
  /* constants/index.js DISPUTE_LOCK_HOURS, read by retrieve.js to set
     is_dispute_unable_to_resolve. */
  var DISPUTE_LOCK_HOURS = 24;

  /* The reasons the server writes when a WORKER raises a review
     (controllers/order/update.js routeToFraudReview). Carried verbatim so the
     app's PL-314 helper (helpers/workerReview.js, a prefix test on this string)
     recognises them the day it is synced in. */
  var NO_SHOW_REASON = {
    age: 'Requester no show - Age restricted order',
    keyword: 'Requester no show - Keyword-flagged order (ID required)'
  };

  function str(v) { return v == null ? '' : String(v); }

  function categoryType(r) {
    if (!r) return null;
    var codes = [r.category, r.cat];
    for (var i = 0; i < codes.length; i++) {
      var c = str(codes[i]).toLowerCase();
      if (CATEGORY_TYPE[c]) return CATEGORY_TYPE[c];
      if (NAME_TYPE[c]) return NAME_TYPE[c];
    }
    var snap = r.reviewSnapshot && str(r.reviewSnapshot.category).toLowerCase();
    return (snap && NAME_TYPE[snap]) || null;
  }

  function isLabor(r) { return categoryType(r) === 'Hourly / Day Labor'; }

  /* RQ-51 (owner, 2026-10-15, "Whole job (app)"): on Yard, Moving and Junk the
     offer the requester types is for the WHOLE job — one Gopher hired, one offer
     paid, never multiplied by crew size. Only Labor is per Gopher × crew. */
  function wholeOffer(r) {
    var each = Number(r && r.perWorkerCost) || 0;
    var crew = isLabor(r) ? (Number(r && r.workersNeeded) || 1) : 1;
    return each * crew;
  }

  function hiredWorker(r) {
    var list = (r && r.interestedWorkers) || [];
    for (var i = 0; i < list.length; i++) if (list[i] && list[i].status === 'hired') return list[i];
    return null;
  }

  function crewLead(r) {
    var live = (r && r.live) || null;
    if (!live) return null;
    if (Array.isArray(live.crew) && live.crew.length) return live.crew[0];
    return live.worker || null;
  }

  function stepDone(r, re) {
    var steps = (r && r.live && r.live.statusSteps) || [];
    for (var i = 0; i < steps.length; i++) {
      if (steps[i] && steps[i].done && re.test(str(steps[i].k))) return true;
    }
    return false;
  }

  /* The server's order state, from where the web's simulation has got to.
     A hire is `accepted` (on demand) or `scheduled` (booked for later) — the
     worker has NOT started (update.js assign_order). It becomes `picked_up`
     only when the worker taps In Progress, `purchased` at the item step, and
     `delivered` when they complete. The web's own step list is the record of
     those taps (startJob writes it; the Go app advances it over the PT bridge). */
  function aasmStateOf(r) {
    if (!r) return null;
    if (r.expired) return 'expired';
    if (r.confirmed || r.awaitingConfirmation) return 'delivered';
    var hired = !!hiredWorker(r) || !!crewLead(r);
    if (!hired) return 'pending';
    if (stepDone(r, /^completed$/i)) return 'delivered';
    if (stepDone(r, /purchas|picked.?up/i)) return 'purchased';
    if (stepDone(r, /^(in-progress|in progress|driver en route|arrived)$/i)) return 'picked_up';
    return r.scheduledForLater ? 'scheduled' : 'accepted';
  }

  /* "405 Shorehouse Way, Raleigh, NC" → { line1: "405 Shorehouse Way" }. */
  function addressOf(v) {
    if (!v) return null;
    if (typeof v === 'object') {
      var l = str(v.line1 || v.street_line1 || v.address || v.label).split(',')[0].trim();
      return l ? { line1: l } : null;
    }
    var s = str(v).split(',')[0].trim();
    if (!s || s === 'Any location') return null;
    return { line1: s };
  }

  /* The server's id is a number that only grows, and Home orders cards newest
     first within a group. The web's ids are "GR-00123" for the seeds but
     "GR-0002" for a request made in this session (it restarts below the seeds),
     so a request made here uses its submit time instead: always newer. */
  function orderIdOf(r) {
    if (r.serverId != null) return Number(r.serverId);
    if (r.submittedAt) return Number(r.submittedAt);
    var m = str(r.id).match(/(\d+)/);
    return m ? Number(m[1]) : 0;
  }

  function iso(v) {
    if (v == null || v === '') return null;
    var t = typeof v === 'number' ? v : Date.parse(v);
    return isFinite(t) ? new Date(t).toISOString() : null;
  }

  /* requestor_alerts — what the server counts as UNVIEWED for the requester
     (retrieve.js, the requestor_alerts query): answers and bids and counters
     only while no worker is assigned; an unanswered cost adjustment; a
     reschedule. An offer is viewed when the requester opens it (the profile, or
     a counter's "What changed" / details), as view_gopher / set_counter_viewed
     mark it on the server. `inbox` is not modelled: the web's Inbox badge
     carries unread messages. */
  function alertsOf(r, assigned) {
    var bids = !!(r.bidsMode || (r.reviewSnapshot && r.reviewSnapshot.bidsMode));
    var open = (r.interestedWorkers || []).filter(function (w) {
      return w && w.status !== 'hired' && !w.viewed;
    }).length;
    var counters = (r.counterOffers || []).filter(function (c) { return c && !c.viewed; }).length;
    return {
      order_gophers: !assigned && !bids ? open : 0,
      bids: !assigned && bids ? open : 0,
      counter: !assigned ? counters : 0,
      cogs: r.pendingAdjustment && !r.pendingAdjustment.viewed ? 1 : 0,
      re_scheduled_request: r.rescheduleRequest && !r.rescheduleRequest.viewed ? 1 : 0
    };
  }

  function build(r, now) {
    now = now == null ? Date.now() : now;
    var aasm = aasmStateOf(r);
    var w = hiredWorker(r);
    var released = !!(r.__ptGopherCancelled && !r.workerCancelChoice);
    /* A worker who cancels is NOT detached: cancel.js keeps gopher_id so the
       cancellation stays attributable (owner, 2026-09-13), and the app's
       "Worker cancelled" page names them. The PT bridge clears the web's
       worker list, so the last assigned worker (remembered by sync) stands in. */
    var lead = crewLead(r) || w || (released ? r.lastGopher || null : null);
    var assigned = !!lead && (aasm !== 'pending' || released);
    var snap = r.reviewSnapshot || {};
    var type = categoryType(r);
    var name = str(lead && lead.name).trim();
    var cog = Number(snap.costOfItems != null ? snap.costOfItems : r.costOfItems) || 0;
    var disputedAt = iso(r.disputedAt);
    var noShow = !!r.noShow;
    var disputed = r.disputeState === 'disputed' || noShow;

    var order = {
      id: orderIdOf(r),
      title: type === 'Other'
        ? 'Other - ' + str(r.descriptionFull || snap.description).trim()
        : (type || str(r.title)),
      category_type: type,
      sub_category_type: r.subCategory || null,
      delivery_needed: r.deliveryNeeded != null ? !!r.deliveryNeeded : undefined,
      aasm_state: aasm,
      payment_status: r.paymentFailed ? 'requires_payment_method'
        : r.confirmed ? 'paid'
        : assigned ? 'authorized' : 'pending',
      stripe_error: r.paymentFailed ? (r.stripeError || null) : null,
      request_schedule_later: !!r.scheduledForLater,
      request_schedule_time: iso(r.requestScheduleTime),
      delivery_eta: iso(r.deliveryEta),
      gopher_id: assigned ? (lead.id || name || 'gopher') : null,
      gopher: assigned ? {
        first_name: name.split(/\s+/)[0] || '',
        last_name: name.split(/\s+/).slice(1).join(' ').replace(/\.$/, ''),
        profile_photo: lead.photo || '',
        average_rating: Number(lead.rating) || null,
        total_ratings: Number(lead.reviews) || 0
      } : null,
      address: addressOf((r.dropoffs || [])[0]) || addressOf(snap.dropoff)
        || addressOf((r.pickups || [])[0]) || addressOf(snap.pickup),
      dropoff_address: addressOf((r.dropoffs || [])[0]) || addressOf(snap.dropoff),
      cost_of_goods: Math.round(cog * 100),
      offer: String(Math.round(wholeOffer(r) * 100)),
      requestor_alerts: alertsOf(r, assigned),
      has_active_cog: !!r.pendingAdjustment,
      disputed: disputed,
      disputed_at: disputedAt,
      dispute_reason: noShow
        ? (r.ageRestricted ? NO_SHOW_REASON.age : NO_SHOW_REASON.keyword)
        : (disputed ? str(r.disputeReason) : null),
      unable_to_dispute: !!r.unableToDispute,
      dispute_resolved_at: iso(r.disputeResolvedAt),
      dispute_resolution: r.disputeResolution || null,
      /* G40-39: true once photos are in or the worker skipped. The web's
         simulated completions (a seed's completionPhotos, the Go app's Complete
         over PT) only ever arrive after that step, so a completed request reads
         resolved unless the record says otherwise. Strict `false` holds the
         confirm screen, exactly as helpers/photoStep.js reads it. */
      photo_step_resolved: aasm === 'delivered' ? r.photoStepResolved !== false : undefined,
      /* The worker walked away (cancel.js keeps the order and stamps
         gopher_released_at; the app's "Worker cancelled" page reads it and the
         worker's reason). "Assign new worker" (keep_listed) clears it. The
         server's release_expires_at deadline is NOT invented here: without the
         server there is no clock to show, so none is shown. */
      gopher_released_at: (r.__ptGopherCancelled && !r.workerCancelChoice)
        ? iso(r.gopherReleasedAt) : null,
      cancellation_reason: r.__ptGopherCancelled ? (r.__ptCancelReason || null) : null,
      requestor_reminded: !!r.noShowReminded,
      requestor_reminded_at: iso(r.noShowRemindedAt),
      updated_at: iso(r.updatedAt || r.submittedAt) || null
    };
    /* retrieve.js sets this only when the order has a disputed_at. */
    if (disputedAt) {
      order.is_dispute_unable_to_resolve =
        (now - Date.parse(disputedAt)) / 3600000 < DISPUTE_LOCK_HOURS;
    }
    return order;
  }

  function sync(r, now) {
    if (!r) return null;
    if (r.order && r.order.__source === 'api') return r.order;
    /* The PT bridge flags a worker's cancel without a time; the first sync
       that sees it stamps one, as the server stamps gopher_released_at. */
    if (r.__ptGopherCancelled && !r.gopherReleasedAt) r.gopherReleasedAt = now == null ? Date.now() : now;
    var lead = crewLead(r) || hiredWorker(r);
    if (lead && lead.name) {
      r.lastGopher = { name: lead.name, photo: lead.photo || '', rating: lead.rating, reviews: lead.reviews, id: lead.id };
    }
    r.order = build(r, now);
    return r.order;
  }

  /* Does GET /orders/v3 put this order on the requester's Home? (The live
     states, and a delivered order only until it is paid; an expired one for a
     day, from Request History — homeCards.recentlyExpired.) */
  function onHome(order, now) {
    if (!order) return false;
    now = now == null ? Date.now() : now;
    if (order.aasm_state === 'expired') {
      var at = Date.parse(order.delivery_eta || order.updated_at || '');
      return isFinite(at) && now - at >= 0 && now - at <= DAY_MS;
    }
    return HOME_STATES.indexOf(order.aasm_state) !== -1
      && HOME_PAYMENT.indexOf(order.payment_status) !== -1;
  }

  var api = {
    sync: sync,
    build: build,
    onHome: onHome,
    aasmStateOf: aasmStateOf,
    categoryType: categoryType,
    wholeOffer: wholeOffer,
    CATEGORY_TYPE: CATEGORY_TYPE,
    NO_SHOW_REASON: NO_SHOW_REASON
  };
  root.GopherDashOrder = api;
  if (typeof module === 'object' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : this);
